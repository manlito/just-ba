"""Regenerates every checked-in residual file.

Usage, from the repository root:

    residuals/symbolic/.venv/bin/python residuals/symbolic/generate.py          # write
    residuals/symbolic/.venv/bin/python residuals/symbolic/generate.py --check  # CI: fail on drift

Generated files are checked in. The generator is a development tool, not a build
dependency (document 03).
"""

import argparse
import pathlib
import sys

import wrenfold

import emit
import priors
import reprojection

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "residuals" / "generated"

BANNER = (
    "// Generated by residuals/symbolic/generate.py with wrenfold {version}. Do not edit.\n"
    "// Source: residuals/symbolic/{source}\n"
)


def _model_table(lang: str) -> str:
    lines = ["// Camera models in this file (COLMAP id, parameters):"]
    for m in reprojection.CAMERA_MODELS:
        lines.append(f"//   {m.name.upper():<15} id {m.colmap_id}: {', '.join(m.params)}")
    return "\n".join(lines) + "\n"


def render_cpu() -> str:
    gen = emit.CpuGenerator()
    parts = [
        BANNER.format(version=wrenfold.__version__, source="reprojection.py"),
        "#pragma once\n\n#include <cmath>\n\n",
        _model_table("cpp"),
        "\nnamespace jba::generated {\n\n",
    ]
    for model in reprojection.CAMERA_MODELS:
        parts.append(emit.generate(reprojection.make_reprojection(model), gen))
        parts.append("\n")
    parts.append("}  // namespace jba::generated\n")
    return "".join(parts)


def render_metal() -> str:
    gen = emit.MetalGenerator()
    parts = [
        BANNER.format(version=wrenfold.__version__, source="reprojection.py"),
        "// Metal Shading Language. Included into kernel sources; instantiate with float.\n",
        "#pragma once\n\n#include <metal_stdlib>\n\n",
        _model_table("metal"),
        "\nnamespace jba_generated {\n\n",
    ]
    for model in reprojection.CAMERA_MODELS:
        parts.append(emit.generate(reprojection.make_reprojection(model), gen))
        parts.append("\n")
    parts.append("}  // namespace jba_generated\n")
    return "".join(parts)


def render_priors_cpu() -> str:
    gen = emit.CpuGenerator()
    parts = [
        BANNER.format(version=wrenfold.__version__, source="priors.py"),
        "#pragma once\n\n#include <cmath>\n\nnamespace jba::generated {\n\n",
    ]
    for func in priors.FUNCTIONS:
        parts.append(emit.generate(func, gen))
        parts.append("\n")
    parts.append("}  // namespace jba::generated\n")
    return "".join(parts)


FILES = {
    OUT / "cpu" / "reprojection_generated.h": render_cpu,
    OUT / "cpu" / "priors_generated.h": render_priors_cpu,
    OUT / "metal" / "reprojection.metal.h": render_metal,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if files are out of date")
    args = parser.parse_args()

    stale = []
    for path, render in FILES.items():
        text = render()
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
